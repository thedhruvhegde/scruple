"""Write CHANGELOG.md from the keyed commit history.

Every commit subject starts with a key (see CLAUDE.md): `[+]` added, `[!]` fixed,
`[~]` changed, `[#]` docs. Commits are grouped by the first tag that contains them,
newest first; commits after the newest tag go under "Unreleased". Subjects without a
key (the history before the convention) go under "Other". Merge commits are skipped.

    uv run python scripts/changelog.py              # rewrite CHANGELOG.md
    uv run python scripts/changelog.py --stdout     # print instead
    uv run python scripts/changelog.py --check      # exit 1 if CHANGELOG.md is stale
    uv run python scripts/changelog.py --notes v0.1.0   # one release, for release notes

The output depends only on the git history, so the same history always gives the
same file.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

SECTIONS: dict[str, str] = {"+": "Added", "!": "Fixed", "~": "Changed", "#": "Docs"}
OTHER = "Other"
ORDER = (*SECTIONS.values(), OTHER)
UNRELEASED = "Unreleased"
KEYED = re.compile(r"^\[([+!~#])\]\s+(\S.*)$")
SEP = "\x1f"

HEADER = (
    "# Changelog\n\n"
    "Generated by `scripts/changelog.py` from the keyed commit history. Do not edit by\n"
    "hand: rerun the script. Keys: `[+]` added, `[!]` fixed, `[~]` changed, `[#]` docs.\n"
)


@dataclass(frozen=True)
class Entry:
    section: str
    text: str
    commit: str = ""


@dataclass(frozen=True)
class Release:
    title: str
    date: str = ""
    entries: tuple[Entry, ...] = field(default_factory=tuple)


def parse_subject(subject: str, commit: str = "") -> Entry:
    """Map one commit subject to its changelog section."""
    s = subject.strip()
    m = KEYED.match(s)
    if m:
        return Entry(SECTIONS[m.group(1)], m.group(2).strip(), commit)
    return Entry(OTHER, s, commit)


def _escape(text: str) -> str:
    # A subject is one line of plain text; keep it from turning into markup.
    return re.sub(r"([\\`*_<>\[\]])", r"\\\1", " ".join(text.split()))


def render(releases: list[Release]) -> str:
    """Markdown for the given releases, in the order given (newest first)."""
    out = [HEADER]
    for rel in releases:
        if not rel.entries:
            continue
        title = f"## {rel.title}" + (f" ({rel.date})" if rel.date else "")
        out.append(f"\n{title}\n")
        for section in ORDER:
            items = [e for e in rel.entries if e.section == section]
            if not items:
                continue
            out.append(f"\n### {section}\n\n")
            for e in items:
                ref = f" ({e.commit[:7]})" if e.commit else ""
                out.append(f"- {_escape(e.text)}{ref}\n")
    return "".join(out)


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(  # noqa: S603 - fixed git arguments, no shell
        ["git", "-C", str(repo), *args],  # noqa: S607 - git on PATH is intended
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def _commits(repo: Path, rev_range: str) -> tuple[Entry, ...]:
    log = _git(repo, "log", "--no-merges", f"--format=%H{SEP}%s", rev_range)
    entries = []
    for line in log.splitlines():
        sha, _, subject = line.partition(SEP)
        if subject.strip():
            entries.append(parse_subject(subject, sha))
    return tuple(entries)


def tags(repo: Path) -> list[tuple[str, str]]:
    """(tag, date of its commit) for tags reachable from HEAD, oldest first."""
    position = {
        sha: i
        for i, sha in enumerate(_git(repo, "rev-list", "--reverse", "--topo-order", "HEAD").split())
    }
    found = []
    for tag in _git(repo, "tag", "--merged", "HEAD").split():
        sha, _, date = _git(repo, "log", "-1", f"--format=%H{SEP}%cs", tag).strip().partition(SEP)
        found.append((position[sha], tag, date))
    return [(tag, date) for _, tag, date in sorted(found)]


def collect(repo: Path) -> list[Release]:
    """Releases from the repository at `repo`, newest first."""
    head = subprocess.run(  # noqa: S603 - fixed git arguments, no shell
        ["git", "-C", str(repo), "rev-parse", "--verify", "-q", "HEAD"],  # noqa: S607
        capture_output=True,
        check=False,
    )
    if head.returncode != 0:  # no commits yet
        return []
    releases: list[Release] = []
    prev = ""
    for tag, date in tags(repo):
        rev_range = f"{prev}..{tag}" if prev else tag
        releases.append(Release(tag, date, _commits(repo, rev_range)))
        prev = tag
    releases.append(Release(UNRELEASED, "", _commits(repo, f"{prev}..HEAD" if prev else "HEAD")))
    return releases[::-1]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    ap.add_argument("--repo", type=Path, default=ROOT)
    ap.add_argument("--output", type=Path, default=None, help="default: <repo>/CHANGELOG.md")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--stdout", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--notes", metavar="TAG", help="print one release's section only")
    args = ap.parse_args(argv)

    releases = collect(args.repo)
    if args.notes:
        chosen = [r for r in releases if r.title == args.notes]
        if not chosen:
            print(f"no release {args.notes!r} in the history", file=sys.stderr)
            return 1
        sys.stdout.write(render(chosen).removeprefix(HEADER).lstrip("\n"))
        return 0
    text = render(releases)
    output: Path = args.output or args.repo / "CHANGELOG.md"
    if args.stdout:
        sys.stdout.write(text)
        return 0
    if args.check:
        current = output.read_text() if output.exists() else ""
        if current != text:
            print(f"{output} is stale; run scripts/changelog.py", file=sys.stderr)
            return 1
        return 0
    output.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
