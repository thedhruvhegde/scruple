"""The TypeScript SDK's types are generated from a snapshot of the OpenAPI schema.

The snapshot must match the live schema, and the generated file must cover it, so a
route or model change cannot silently leave the TypeScript client behind. To fix a
failure: `uv run python sdk/typescript/scripts/openapi.py`, then
`cd sdk/typescript && npm run generate`.
"""

from __future__ import annotations

import importlib.util
import json
import re
import sys
import tomllib
from pathlib import Path
from types import ModuleType
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SDK = ROOT / "sdk" / "typescript"
FIX = (
    "run `uv run python sdk/typescript/scripts/openapi.py`, "
    "then `npm run generate` in sdk/typescript"
)


def _script() -> ModuleType:
    spec = importlib.util.spec_from_file_location("sdk_openapi", SDK / "scripts" / "openapi.py")
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def _strip_version(schema: dict[str, Any]) -> dict[str, Any]:
    out = json.loads(json.dumps(schema))
    out["info"].pop("version", None)
    return dict(out)


def _snapshot() -> dict[str, Any]:
    data: dict[str, Any] = json.loads((SDK / "openapi.json").read_text())
    return data


def test_snapshot_matches_the_live_schema() -> None:
    live = _script().live_schema()
    assert _strip_version(_snapshot()) == _strip_version(live), FIX


def test_snapshot_is_in_canonical_form() -> None:
    mod = _script()
    assert (SDK / "openapi.json").read_text() == mod.render(_snapshot()), FIX


def test_generated_types_cover_every_path_and_schema() -> None:
    ts = (SDK / "src" / "schema.ts").read_text()
    assert ts.startswith("/**\n * This file was auto-generated by openapi-typescript.")
    snap = _snapshot()
    for path in snap["paths"]:
        assert f'"{path}": {{' in ts, (path, FIX)
    declared = set(re.findall(r"^ {8}([A-Za-z0-9_\"-]+): ", ts, flags=re.M))
    for name in snap["components"]["schemas"]:
        key = f'"{name}"' if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) else name
        assert key in declared, (name, FIX)
    operations = {op["operationId"] for item in snap["paths"].values() for op in item.values()}
    for op in operations:
        assert f"    {op}: {{" in ts, (op, FIX)


def test_sdk_version_tracks_the_engine_version() -> None:
    pkg = json.loads((SDK / "package.json").read_text())
    engine = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]["version"]
    assert pkg["version"] == engine
    # No licence chosen yet: the package must not be publishable by accident.
    assert pkg["private"] is True
    assert "license" not in pkg


def test_sdk_dev_dependencies_are_pinned_exactly() -> None:
    pkg = json.loads((SDK / "package.json").read_text())
    for name, version in pkg["devDependencies"].items():
        assert re.fullmatch(r"\d+\.\d+\.\d+", version), (name, version)
    assert (SDK / "package-lock.json").is_file()
