"""Write a synthetic bank statement as camt.053 or BAI2, and read it back with the parsers.

The writers produce files in the shapes `scruple.ingest.bank.parse_camt053` and
`parse_bai2` accept (the parsers were checked against public sample files, see
tests/fixtures/bank/README.md). The environment never hands the agent the generator's
`BankLine`s: it parses the file, so the reconciler works from exactly what a bank file
would give it, and a round trip test pins that nothing is lost.

camt.053.001.02: one `Stmt` with `OPBD` and `CLBD` balances and one `Ntry` per line
(`NtryRef` and `EndToEndId` carry the payment reference, `AcctSvcrRef` the bank's,
`BkTxCd/Prtry/Cd` a proprietary type code, `AddtlNtryInf` the text).

BAI2: one group per booking day (BAI2 dates a group, not a transaction), with the
opening (010) and closing (015) ledger balances of that day and one 16 record per
line: type 195 for credits, 495 for debits and 698 for bank charges (codes from
ministryofjustice/bai2's table as vendored in `scruple.ingest.bank.bai2_codes`;
ASSUMPTION AR-3: chosen for their direction only, not for their exact BAI meaning).
Control totals and record counts follow the parser's integrity rules.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import date
from itertools import groupby
from xml.sax.saxutils import escape

from pydantic import BaseModel, ConfigDict

from scruple.ingest.bank import parse_bai2, parse_camt053
from scruple.ingest.bank.models import BankStatement
from scruple.sim.fx import EXPONENT
from scruple.sim.recon.models import BankLine

CAMT_NS = "urn:iso:std:iso:20022:tech:xsd:camt.053.001.02"
BAI2_CREDIT, BAI2_DEBIT, BAI2_FEE = "195", "495", "698"


class StatementLine(BaseModel):
    """A statement line as the agent sees it (parsed from the bank file)."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    line_id: str
    booking_date: date | None
    amount_minor: int  # signed: positive is a credit
    reference: str | None
    bank_ref: str | None
    type_code: str | None
    description: str | None


class ParsedStatement(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    format: str
    account_id: str
    currency: str
    opening_balance_minor: int | None
    closing_balance_minor: int | None
    lines: tuple[StatementLine, ...]


def _decimal(amount_minor: int, currency: str) -> str:
    exp = EXPONENT[currency]
    a = abs(amount_minor)
    if exp == 0:
        return str(a)
    return f"{a // 10**exp}.{a % 10**exp:0{exp}d}"


def write_camt053(
    statement_id: str,
    account_id: str,
    currency: str,
    period: tuple[date, date],
    opening_minor: int,
    lines: Sequence[BankLine],
) -> str:
    closing = opening_minor + sum(x.amount_minor for x in lines)

    def bal(code: str, amount: int, on: date) -> str:
        ind = "CRDT" if amount >= 0 else "DBIT"
        return (
            f"<Bal><Tp><CdOrPrtry><Cd>{code}</Cd></CdOrPrtry></Tp>"
            f'<Amt Ccy="{currency}">{_decimal(amount, currency)}</Amt>'
            f"<CdtDbtInd>{ind}</CdtDbtInd><Dt><Dt>{on.isoformat()}</Dt></Dt></Bal>"
        )

    out = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- SYNTHETIC statement generated by scruple.sim.recon; not from any bank. -->",
        f'<Document xmlns="{CAMT_NS}"><BkToCstmrStmt>',
        f"<GrpHdr><MsgId>{escape(statement_id)}</MsgId>"
        f"<CreDtTm>{period[1].isoformat()}T23:00:00</CreDtTm></GrpHdr>",
        f"<Stmt><Id>{escape(statement_id)}</Id>",
        f"<Acct><Id><Othr><Id>{escape(account_id)}</Id></Othr></Id><Ccy>{currency}</Ccy></Acct>",
        bal("OPBD", opening_minor, period[0]),
        bal("CLBD", closing, period[1]),
    ]
    for x in lines:
        ind = "CRDT" if x.amount_minor >= 0 else "DBIT"
        out.append(
            f"<Ntry><NtryRef>{escape(x.reference)}</NtryRef>"
            f'<Amt Ccy="{currency}">{_decimal(x.amount_minor, currency)}</Amt>'
            f"<CdtDbtInd>{ind}</CdtDbtInd><Sts>BOOK</Sts>"
            f"<BookgDt><Dt>{x.booking_date.isoformat()}</Dt></BookgDt>"
            f"<ValDt><Dt>{x.booking_date.isoformat()}</Dt></ValDt>"
            f"<AcctSvcrRef>{escape(x.bank_ref)}</AcctSvcrRef>"
            f"<BkTxCd><Prtry><Cd>{escape(x.type_code)}</Cd></Prtry></BkTxCd>"
            f"<NtryDtls><TxDtls><Refs><EndToEndId>{escape(x.reference)}</EndToEndId></Refs>"
            f"</TxDtls></NtryDtls>"
            f"<AddtlNtryInf>{escape(x.description)}</AddtlNtryInf></Ntry>"
        )
    out.append("</Stmt></BkToCstmrStmt></Document>")
    return "\n".join(out) + "\n"


def bai2_code(x: BankLine) -> str:
    if x.type_code == "FEE":
        return BAI2_FEE
    return BAI2_CREDIT if x.amount_minor >= 0 else BAI2_DEBIT


def write_bai2(
    sender: str,
    account_id: str,
    currency: str,
    created: date,
    opening_minor: int,
    lines: Sequence[BankLine],
) -> str:
    rows = [f"01,{sender},SCRUPLE,{created:%y%m%d},2300,1,,,2/"]
    file_total = groups = 0
    balance = opening_minor
    for day, items in groupby(lines, key=lambda x: x.booking_date):
        day_lines = list(items)
        close = balance + sum(x.amount_minor for x in day_lines)
        acct = [f"03,{account_id},{currency},010,{balance},,,015,{close},,/"]
        total = balance + close
        for x in day_lines:
            text = x.description.replace(",", " ").replace("/", " ")
            acct.append(
                f"16,{bai2_code(x)},{abs(x.amount_minor)},,{x.bank_ref},{x.reference},{text}"
            )
            total += abs(x.amount_minor)
        acct.append(f"49,{total},{len(acct) + 1}/")
        group = [f"02,SCRUPLE,{sender},1,{day:%y%m%d},,{currency},2/", *acct]
        group.append(f"98,{total},1,{len(group) + 1}/")
        rows += group
        file_total += total
        groups += 1
        balance = close
    rows.append(f"99,{file_total},{groups},{len(rows) + 1}/")
    return "\n".join(rows) + "\n"


def _lines(stmts: Sequence[BankStatement]) -> tuple[StatementLine, ...]:
    out: list[StatementLine] = []
    for e in (e for s in stmts for e in s.entries):
        out.append(
            StatementLine(
                line_id=f"S-{len(out) + 1:03d}",
                booking_date=e.booking_date,
                amount_minor=e.signed_minor,
                reference=e.end_to_end_id or e.customer_ref,
                bank_ref=e.bank_ref,
                type_code=e.type_code,
                description=e.description,
            )
        )
    return tuple(out)


def _balance(stmt: BankStatement, kinds: tuple[str, ...]) -> int | None:
    return next((b.amount_minor for b in stmt.balances if b.kind in kinds), None)


def read_statement(fmt: str, text: str) -> ParsedStatement:
    """Parse the bank's file with the real parsers. Raises `IngestError` on bad input."""
    if fmt == "camt053":
        stmts = parse_camt053(text)
    elif fmt == "bai2":
        stmts = parse_bai2(text)
    else:
        raise ValueError(f"unknown statement format {fmt!r}")
    if not stmts:  # pragma: no cover - both parsers refuse empty files
        raise ValueError("no statement in the file")
    return ParsedStatement(
        format=fmt,
        account_id=stmts[0].account_id,
        currency=stmts[0].currency,
        opening_balance_minor=_balance(stmts[0], ("OPBD", "010")),
        closing_balance_minor=_balance(stmts[-1], ("CLBD", "015")),
        lines=_lines(stmts),
    )


