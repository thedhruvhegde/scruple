"""Per-tenant integration settings, and where their secrets come from.

Settings are data a tenant admin may change (`POST /integrations/settings`); secrets
are not. A setting names a secret by environment variable, and the variable must
carry the tenant's own prefix:

    tenant "bank-a"  ->  SCRUPLE_SECRET_BANK_A_<anything>

so one tenant's admin can never point an integration at a variable that holds the
database password or another tenant's token (and send it to a host they control).
Tenant ids are `[a-z0-9-]`, so the upper-cased, `-`->`_` prefix is unique per tenant.

Webhook signing secrets are generated by scruple (`scruple.integrations.webhooks`)
and stored sealed with the field cipher (`SCRUPLE_FIELD_KEYS`); approval links are
keyed by `SCRUPLE_APPROVAL_LINK_KEYS`. Both are deployment keys, not tenant settings.
"""

from __future__ import annotations

import re
from collections.abc import Mapping

from pydantic import BaseModel, ConfigDict, Field, model_validator

from scruple.auth.models import Permission
from scruple.auth.rbac import SeparationOfDutiesError, check_separation, permissions_for
from scruple.registry.models import ACTOR_PATTERN

SECRET_ENV_PATTERN = r"^SCRUPLE_SECRET_[A-Z0-9_]{1,96}$"  # noqa: S105 - a name pattern
HTTPS_URL = r"^https://[A-Za-z0-9.-]+(:[0-9]{2,5})?(/[A-Za-z0-9._~/-]*)?$"
UUID = r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$"


class SecretError(LookupError):
    """A named secret is missing or outside the tenant's prefix. Never holds a value."""


def tenant_secret_prefix(tenant: str) -> str:
    return "SCRUPLE_SECRET_" + tenant.upper().replace("-", "_") + "_"


def resolve_secret(name: str, tenant: str, env: Mapping[str, str]) -> str:
    if not re.match(SECRET_ENV_PATTERN, name) or not name.startswith(tenant_secret_prefix(tenant)):
        raise SecretError(f"{name} is not one of tenant {tenant}'s secrets")
    value = env.get(name, "")
    if not value:
        raise SecretError(f"secret {name} is not set")
    return value


class _In(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class SlackApprover(_In):
    """A Slack user who may approve, and the scruple principal they act as."""

    slack_user_id: str = Field(pattern=r"^[UW][A-Z0-9]{2,20}$")
    subject: str = Field(pattern=ACTOR_PATTERN)
    roles: tuple[str, ...] = Field(default=("approver",), min_length=1, max_length=10)

    @model_validator(mode="after")
    def _can_approve(self) -> SlackApprover:
        granted = permissions_for(self.roles, ())
        if Permission.APPROVE not in granted:
            raise ValueError(f"{self.subject}: roles {list(self.roles)} do not grant approve")
        try:
            check_separation(granted)
        except SeparationOfDutiesError as exc:
            raise ValueError(f"{self.subject}: {exc}") from None
        return self

    @property
    def permissions(self) -> frozenset[Permission]:
        return permissions_for(self.roles, ())


class SlackConfig(_In):
    team_id: str = Field(pattern=r"^T[A-Z0-9]{2,20}$")
    channel: str = Field(pattern=r"^[CG][A-Z0-9]{2,20}$")
    bot_token_env: str = Field(pattern=SECRET_ENV_PATTERN)
    # One, or two while the signing secret is rotated.
    signing_secret_envs: tuple[str, ...] = Field(min_length=1, max_length=2)
    interactive: bool = True  # Approve/Reject buttons answered by the interactivity URL
    links: bool = False  # also DM each approver their own signed approve/reject links
    public_base_url: str | None = Field(default=None, pattern=HTTPS_URL)
    link_ttl_seconds: int = Field(default=24 * 3600, ge=300, le=7 * 24 * 3600)
    approvers: tuple[SlackApprover, ...] = Field(default=(), max_length=200)

    @model_validator(mode="after")
    def _consistent(self) -> SlackConfig:
        for env in self.signing_secret_envs:
            if not re.match(SECRET_ENV_PATTERN, env):
                raise ValueError(f"signing secret variable {env!r} must match {SECRET_ENV_PATTERN}")
        ids = [a.slack_user_id for a in self.approvers]
        subjects = [a.subject for a in self.approvers]
        if len(set(ids)) != len(ids) or len(set(subjects)) != len(subjects):
            raise ValueError("each Slack user and each subject may appear once")
        if self.links and not self.public_base_url:
            raise ValueError("links need public_base_url (where scruple's API is reachable)")
        return self

    def approver_for(self, slack_user_id: str) -> SlackApprover | None:
        return next((a for a in self.approvers if a.slack_user_id == slack_user_id), None)

    def approver_named(self, subject: str) -> SlackApprover | None:
        return next((a for a in self.approvers if a.subject == subject), None)


class JiraConfig(_In):
    """Jira Cloud, REST API v3, basic auth with an Atlassian API token."""

    base_url: str = Field(pattern=HTTPS_URL)  # https://<site>.atlassian.net
    email: str = Field(pattern=r"^[^@\s]{1,64}@[A-Za-z0-9.-]{1,190}$")
    api_token_env: str = Field(pattern=SECRET_ENV_PATTERN)
    project_key: str = Field(pattern=r"^[A-Z][A-Z0-9_]{1,9}$")
    issue_type: str = Field(default="Task", min_length=1, max_length=60)
    labels: tuple[str, ...] = Field(default=("scruple",), max_length=10)

    @model_validator(mode="after")
    def _labels(self) -> JiraConfig:
        if any(not re.match(r"^[A-Za-z0-9_.-]{1,60}$", label) for label in self.labels):
            raise ValueError("Jira labels have no spaces (letters, digits, _ . -)")
        return self


class LinearConfig(_In):
    """Linear's GraphQL API with a personal API key."""

    api_key_env: str = Field(pattern=SECRET_ENV_PATTERN)
    team_id: str = Field(pattern=UUID)


class IntegrationSettings(_In):
    slack: SlackConfig | None = None
    jira: JiraConfig | None = None
    linear: LinearConfig | None = None

    def secret_names(self) -> tuple[str, ...]:
        out: list[str] = []
        if self.slack:
            out += [self.slack.bot_token_env, *self.slack.signing_secret_envs]
        if self.jira:
            out.append(self.jira.api_token_env)
        if self.linear:
            out.append(self.linear.api_key_env)
        return tuple(out)

    def check_secret_names(self, tenant: str) -> None:
        """Every named secret must be the tenant's (ValueError otherwise)."""
        prefix = tenant_secret_prefix(tenant)
        for name in self.secret_names():
            if not name.startswith(prefix):
                raise ValueError(f"{name}: tenant {tenant}'s secrets start with {prefix}")


