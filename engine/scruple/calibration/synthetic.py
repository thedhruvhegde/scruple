"""Scruple's history simulator: synthetic dispute histories drawn from a profile.

SYNTHETIC. Nothing produced here is customer data. Every generated Stripe object
carries `metadata.scruple_synthetic = "true"` and ids starting `dp_synth` / `ch_synth` /
`txn_synth`, so a synthetic history can never be mistaken for an export.

Two renderings of the same draws:

- `generate_history`: `ExternalCase`s plus `LedgerMovement`s (any reason keys).
- `stripe_disputes`: Stripe-shaped dispute JSON objects (Stripe reason values only)
  that `scruple.ingest.stripe.ingest_dispute` maps back to exactly the same records.

Generative model per case (parameters from `CalibrationProfile`):
reason by weight; network by weight; amount log-normal (at least 50 minor units);
opened uniformly over `span_days`; inquiry with `p_inquiry` (then closed, or still open
with `p_open`); otherwise a chargeback, still open with `p_open`, else contested with
`p_contest[reason]`. A contested case carries the key evidence field with
`p_key_evidence` and an unrelated field with probability 1/2, is late with `p_late`, and
is won with `p_win_with_key` or `p_win_without_key`. An uncontested chargeback is lost.
Each chargeback has a dispute debit (amount plus `dispute_fee_minor`) when it opens and,
when won, a reinstatement credit 30 to 75 days later. A share `p_repeat` of cases
reuses an earlier charge (a second dispute on one payment). The evidence due date is
18 days after opening. Fixed constants here are synthetic (ASSUMPTION).
"""

from __future__ import annotations

import math
import random
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Any

from pydantic import BaseModel, ConfigDict

from scruple.calibration.aggregates import OTHER, UNKNOWN
from scruple.calibration.profile import CalibrationProfile
from scruple.ingest.models import ExternalCase, LedgerMovement, MovementKind
from scruple.ingest.stripe.mapping import EVIDENCE_FIELDS, REASON_MAP, STATUS_MAP

SYNTHETIC_LABEL = (
    "SYNTHETIC: generated by scruple.calibration.synthetic from a calibration profile; "
    "not customer data"
)
SYNTHETIC_METADATA = {"scruple_synthetic": "true"}
DEFAULT_START = datetime(2025, 1, 1, tzinfo=UTC)
DUE_DAYS = 18
NOISE_FIELDS = ("uncategorized_text", "receipt")
MIN_AMOUNT = 50


class SyntheticHistory(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    label: str = SYNTHETIC_LABEL
    seed: int
    cases: tuple[ExternalCase, ...]
    movements: tuple[LedgerMovement, ...] = ()


@dataclass(frozen=True)
class _Draw:
    i: int
    dispute_id: str
    charge_id: str
    reason: str
    network: str
    amount: int
    created: int
    status: str  # a Stripe dispute status value
    submitted: bool
    late: bool
    fields: tuple[str, ...]
    fee: int
    credit_at: int | None


def _draws(
    profile: CalibrationProfile,
    n: int,
    seed: int,
    start: datetime,
    span_days: int,
    p_repeat: float,
) -> list[_Draw]:
    if n < 0 or span_days < 1 or not 0 <= p_repeat <= 1:
        raise ValueError("n >= 0, span_days >= 1 and p_repeat in [0, 1] are required")
    rng = random.Random(f"scruple.calibration.synthetic:{seed}")
    reasons = sorted(profile.reasons)
    r_weights = [profile.reasons[r].weight for r in reasons]
    nets = sorted(profile.network_weights)
    n_weights = [profile.network_weights[x] for x in nets]
    t0 = int(start.timestamp())
    charges: list[str] = []
    out: list[_Draw] = []
    for i in range(n):
        reason = rng.choices(reasons, weights=r_weights, k=1)[0]
        rp = profile.reasons[reason]
        net = rng.choices(nets, weights=n_weights, k=1)[0]
        amount = max(
            MIN_AMOUNT, round(math.exp(rng.gauss(profile.amount_log_mean, profile.amount_log_sd)))
        )
        created = t0 + rng.randrange(span_days * 86_400)
        if charges and rng.random() < p_repeat:
            charge = charges[rng.randrange(len(charges))]
        else:
            charge = f"ch_synth{seed}x{i:06d}"
            charges.append(charge)
        submitted = late = False
        fields: tuple[str, ...] = ()
        credit_at: int | None = None
        fee = 0
        if rng.random() < profile.p_inquiry:
            status = "warning_needs_response" if rng.random() < profile.p_open else "warning_closed"
        else:
            fee = profile.dispute_fee_minor
            if rng.random() < profile.p_open:
                status = "needs_response"
            elif rng.random() < rp.p_contest:
                submitted = True
                has_key = rp.key_evidence is not None and rng.random() < rp.p_key_evidence
                noise = next(f for f in NOISE_FIELDS if f != rp.key_evidence)
                picked = {rp.key_evidence} if has_key and rp.key_evidence else set()
                if rng.random() < 0.5:
                    picked.add(noise)
                fields = tuple(sorted(picked))
                late = rng.random() < profile.p_late
                p = rp.p_win_with_key if has_key else rp.p_win_without_key
                if rng.random() < p:
                    status = "won"
                    credit_at = created + rng.randint(30, 75) * 86_400
                else:
                    status = "lost"
            else:
                status = "lost"
        out.append(
            _Draw(
                i=i,
                dispute_id=f"dp_synth{seed}x{i:06d}",
                charge_id=charge,
                reason=reason,
                network=UNKNOWN if net == OTHER else net,
                amount=amount,
                created=created,
                status=status,
                submitted=submitted,
                late=late,
                fields=fields,
                fee=fee,
                credit_at=credit_at,
            )
        )
    return out


def _ts(seconds: int) -> datetime:
    return datetime.fromtimestamp(seconds, UTC)


def _case(d: _Draw, currency: str, source: str) -> ExternalCase:
    stage, state = STATUS_MAP[d.status]
    return ExternalCase(
        source=source,
        external_id=d.dispute_id,
        payment_ref=d.charge_id,
        stage=stage,
        state=state,
        reason_code=REASON_MAP.get(d.reason),
        source_reason=d.reason,
        network=d.network,
        network_reason_code=None,
        amount_minor=d.amount,
        currency=currency,
        opened_at=_ts(d.created),
        evidence_due_at=_ts(d.created + DUE_DAYS * 86_400),
        evidence_fields=d.fields,
        evidence_submitted=d.submitted,
        evidence_past_due=d.late,
    )


def _movements(d: _Draw, currency: str, source: str) -> list[LedgerMovement]:
    if d.status.startswith("warning_"):
        return []
    out = [
        LedgerMovement(
            source=source,
            external_id=f"txn_synth{d.dispute_id[8:]}d",
            case_external_id=d.dispute_id,
            payment_ref=d.charge_id,
            kind=MovementKind.DISPUTE_DEBIT,
            amount_minor=-d.amount,
            fee_minor=d.fee,
            net_minor=-d.amount - d.fee,
            currency=currency,
            occurred_at=_ts(d.created),
            category="dispute",
        )
    ]
    if d.credit_at is not None:
        out.append(
            LedgerMovement(
                source=source,
                external_id=f"txn_synth{d.dispute_id[8:]}c",
                case_external_id=d.dispute_id,
                payment_ref=d.charge_id,
                kind=MovementKind.DISPUTE_CREDIT,
                amount_minor=d.amount,
                fee_minor=0,
                net_minor=d.amount,
                currency=currency,
                occurred_at=_ts(d.credit_at),
                category="dispute_reversal",
            )
        )
    return out


def generate_history(
    profile: CalibrationProfile,
    n: int,
    seed: int,
    *,
    source: str = "synthetic",
    start: datetime = DEFAULT_START,
    span_days: int = 365,
    p_repeat: float = 0.02,
) -> SyntheticHistory:
    """Deterministic in every argument."""
    ccy = profile.currency
    draws = _draws(profile, n, seed, start, span_days, p_repeat)
    return SyntheticHistory(
        seed=seed,
        cases=tuple(_case(d, ccy, source) for d in draws),
        movements=tuple(m for d in draws for m in _movements(d, ccy, source)),
    )


def _bt(m: LedgerMovement) -> dict[str, Any]:
    ccy = m.currency.lower()
    return {
        "id": m.external_id,
        "object": "balance_transaction",
        "amount": m.amount_minor,
        "currency": ccy,
        "created": int(m.occurred_at.timestamp()),
        "fee": m.fee_minor,
        "fee_details": (
            [{"amount": m.fee_minor, "currency": ccy, "type": "stripe_fee"}] if m.fee_minor else []
        ),
        "net": m.net_minor,
        "reporting_category": m.category,
        "status": "available",
        "type": "adjustment",
    }


def stripe_disputes(
    profile: CalibrationProfile,
    n: int,
    seed: int,
    *,
    start: datetime = DEFAULT_START,
    span_days: int = 365,
    p_repeat: float = 0.02,
) -> list[dict[str, Any]]:
    """Stripe-shaped dispute objects (SYNTHETIC). Reasons must be Stripe reason values."""
    bad = sorted(r for r in profile.reasons if r not in REASON_MAP)
    if bad:
        raise ValueError(f"not Stripe dispute reasons: {bad}")
    ccy = profile.currency
    out: list[dict[str, Any]] = []
    for d in _draws(profile, n, seed, start, span_days, p_repeat):
        evidence: dict[str, Any] = {f: None for f in EVIDENCE_FIELDS}
        for f in d.fields:
            evidence[f] = "synthetic"
        out.append(
            {
                "id": d.dispute_id,
                "object": "dispute",
                "amount": d.amount,
                "currency": ccy.lower(),
                "created": d.created,
                "charge": d.charge_id,
                "reason": d.reason,
                "status": d.status,
                "livemode": False,
                "is_charge_refundable": False,
                "balance_transactions": [_bt(m) for m in _movements(d, ccy, "stripe")],
                "evidence": evidence,
                "evidence_details": {
                    "due_by": d.created + DUE_DAYS * 86_400,
                    "has_evidence": bool(d.fields),
                    "past_due": d.late,
                    "submission_count": 1 if d.submitted else 0,
                },
                "payment_method_details": {
                    "type": "card",
                    "card": {
                        "brand": d.network,
                        "case_type": "inquiry" if d.status.startswith("warning_") else "chargeback",
                        "network": d.network,
                        "network_reason_code": None,
                    },
                },
                "metadata": dict(SYNTHETIC_METADATA),
            }
        )
    return out


